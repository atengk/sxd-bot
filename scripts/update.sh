#!/usr/bin/env bash
# ==============================================================================
# 脚本名称: update.sh
# 脚本作用: 神仙道自动化服务 (sxd-bot) 生产环境一键无感拉取更新与重启
#
# @author Ateng
# @since 2026-10-17
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "=================================================="
echo "🚀 开始更新神仙道自动化助手 (sxd-bot) 生产服务..."
echo "=================================================="

# 1. 拉取最新容器镜像
echo ">>> [1/3] 拉取最新生产容器镜像..."
docker compose pull

# 2. 启动/重载容器
echo ">>> [2/3] 正在无感启动最新容器服务..."
docker compose up -d --remove-orphans

# 3. 清理旧版本镜像缓存
echo ">>> [3/3] 清理旧版本镜像缓存..."
docker image prune -f

echo "=================================================="
echo "✅ 更新完毕！当前容器运行状态与健康检查:"
echo "=================================================="
docker compose ps
